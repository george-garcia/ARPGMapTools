#!/usr/bin/env node
// Computes an act's zone graph from its zone file: every link's compass bearing and straight-line distance, measured on
// the map, not eyeballed. Level design's rule T6 needs the bearing: a zone's exit faces the next zone's direction on
// the act's world map.
//
// Usage: node .claude/skills/arpg-cartography/scripts/zone_graph.mjs world/acts/act1.json [--md out.md] [--json out.json]
//
// Zone file format (world/acts/<act>.json):
// {
//   "act": "Act I", "frame": "act1",
//   "zones": [ { "id": "z02", "name": "Slums", "role": "hub", "anchor": [0.255, 0.445], "status": "locked", "note": "…" } ],
//   "links": [ { "from": "z01", "to": "z02", "status": "decided" | "proposed" | "open", "via": "main road", "source": "…" } ]
// }
// anchor: frame-local 0-1 (x west to east, y north to south), the zone's centre of gravity on the map.
// Distances use the frame's sizeKm from world/frames.json; they are lore scale only and never set a zone's size.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../../../..");
const args = process.argv.slice(2);
const file = args.find(a => !a.startsWith("--") && !args[args.indexOf(a) - 1]?.startsWith("--"));
if (!file) {
  console.error("Usage: zone_graph.mjs <world/acts/act.json> [--md out.md] [--json out.json]");
  process.exit(2);
}
const option = name => (args.includes(name) ? args[args.indexOf(name) + 1] : undefined);

const act = JSON.parse(readFileSync(resolve(root, file), "utf8"));
const frames = JSON.parse(readFileSync(join(root, "world/frames.json"), "utf8"));
const frame = frames[act.frame];
if (!frame) throw new Error(`Unknown frame "${act.frame}" (world/frames.json)`);
const [widthKm, heightKm] = frame.sizeKm;

const POINTS = ["N", "NNE", "NE", "ENE", "E", "ESE", "SE", "SSE", "S", "SSW", "SW", "WSW", "W", "WNW", "NW", "NNW"];
const compass = deg => POINTS[Math.round(deg / 22.5) % 16];

const problems = [];
const zones = new Map();
for (const zone of act.zones ?? []) {
  if (zones.has(zone.id)) problems.push(`duplicate zone id ${zone.id}`);
  const [u, v] = zone.anchor ?? [];
  if (!(u >= 0 && u <= 1 && v >= 0 && v <= 1)) problems.push(`${zone.id}: anchor must be frame-local 0-1, got ${JSON.stringify(zone.anchor)}`);
  zones.set(zone.id, zone);
}

const rows = [];
for (const link of act.links ?? []) {
  const a = zones.get(link.from);
  const b = zones.get(link.to);
  if (!a || !b) {
    problems.push(`link ${link.from} -> ${link.to}: unknown zone`);
    continue;
  }
  if (!["decided", "proposed", "open"].includes(link.status)) problems.push(`link ${link.from} -> ${link.to}: status must be decided, proposed or open`);
  const east = (b.anchor[0] - a.anchor[0]) * widthKm;
  const north = (a.anchor[1] - b.anchor[1]) * heightKm;
  const bearing = Math.round(((((Math.atan2(east, north) * 180) / Math.PI + 360) % 360) * 10)) / 10 % 360;
  const km = Math.round(Math.hypot(east, north));
  rows.push({ ...link, fromName: a.name, toName: b.name, bearing, back: Math.round(((bearing + 180) % 360) * 10) / 10, compass: compass(bearing), backCompass: compass((bearing + 180) % 360), km });
}

const linked = new Set(rows.flatMap(r => [r.from, r.to]));
for (const id of zones.keys()) if (!linked.has(id)) problems.push(`${id} (${zones.get(id).name}) has no link`);

const md = [
  `# ${act.act ?? act.frame}: zone graph`,
  "",
  `Generated by \`.claude/skills/arpg-cartography/scripts/zone_graph.mjs\` from \`${file}\`. Bearings are degrees clockwise`,
  "from map north, measured between the zones' anchors on the map; a zone's exit faces the bearing to the next zone",
  "(level design T6). Distances are lore scale only: they never set a zone's size or walking time.",
  "",
  "| Zone | Name | Role | Status | Anchor (frame 0-1) |",
  "|---|---|---|---|---|",
  ...[...zones.values()].map(z => `| ${z.id} | ${z.name} | ${z.role ?? ""} | ${z.status ?? ""} | ${z.anchor.join(", ")} |`),
  "",
  "| From | To | Exit bearing | Return bearing | Lore km | Link status | Via | Source |",
  "|---|---|---|---|---|---|---|---|",
  ...rows.map(r => `| ${r.fromName} | ${r.toName} | ${r.bearing}° ${r.compass} | ${r.back}° ${r.backCompass} | ${r.km} | ${r.status} | ${r.via ?? ""} | ${r.source ?? ""} |`),
  "",
  problems.length ? `**Problems:**\n${problems.map(p => `- ${p}`).join("\n")}` : "No problems: every zone is linked and every anchor is inside the frame.",
  ""
].join("\n");

const out = { act: act.act, frame: act.frame, zones: [...zones.values()], links: rows, problems };
if (option("--md")) writeFileSync(resolve(root, option("--md")), md);
if (option("--json")) writeFileSync(resolve(root, option("--json")), JSON.stringify(out, null, 2));
if (!option("--md") && !option("--json")) process.stdout.write(md);
process.exitCode = problems.length ? 1 : 0;
