export function compileHistory() {
  const ledger = JSON.parse(readFileSync(join(root, "world/history/events.json"), "utf8"));
  const frames = JSON.parse(readFileSync(join(root, "world/frames.json"), "utf8"));
  const out = Object.fromEntries(ERAS.map(era => [era, { terrain: [], ground: [], notes: [] }]));
  const ids = new Set();
  for (const event of ledger.events) {
    if (ids.has(event.id)) throw new Error(`Duplicate event id "${event.id}"`);
    ids.add(event.id);
    if (!["test", "proposed", "canon"].includes(event.status)) throw new Error(`Event "${event.id}": status must be test, proposed or canon`);
    if (!ledger.eras[event.era]) throw new Error(`Event "${event.id}": unknown era "${event.era}"`);
    const rules = KINDS[event.kind];
    if (!rules) throw new Error(`Event "${event.id}": unknown kind "${event.kind}" (known: ${Object.keys(KINDS).join(", ")})`);
    const frame = frames[event.frame];
    if (!frame) throw new Error(`Event "${event.id}": unknown frame "${event.frame}"`);
    const ops = rules(event, frame.sizeKm, ledger);
    for (const era of ERAS) for (const slot of Object.keys(SLOTS)) out[era][slot].push(...(ops[era]?.[slot] ?? []));
  }
  const written = [];
  for (const era of ERAS) {
    if (out[era].terrain.length) out[era].terrain.push({ id: `history.${era}.finalize`, tool: "finalize_terrain", note: "Rebuild lakes, rivers and biomes from the aged terrain, before the era's climate and water", args: {} });
    for (const [slot, file] of Object.entries(SLOTS)) {
      const path = join(root, "world/eras", era, file);
      const ops = out[era][slot];
      if (!ops.length) {
        if (existsSync(path)) rmSync(path);
        continue;
      }
      writeFileSync(path, JSON.stringify(ops.map(op => ({ ...op, generated: HEADER })), null, 2) + "\n");
      written.push(`world/eras/${era}/${file}`);
    }
  }
  return written;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  console.log(`History ops written: ${compileHistory().join(", ") || "none"}`);
}
