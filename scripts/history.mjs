// Turns the history ledger (world/history/events.json) into op files that the world build replays:
//   world/eras/<era>/00-history.json  terrain (sculpt, then one finalize_terrain), before the era's climate and water
//   world/eras/<era>/35-history.json  biomes and lakes, after the era's own biome paint
//   world/eras/<era>/65-history.json  markers and labels
// The before era shows each event's place as it was; the now era shows what the event left after the years since.
// Each event kind is a set of aging rules, written below with the physical reason for each step.
// Usage: node scripts/history.mjs   (scripts/build-world.mjs runs it before every build)
import { existsSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SLOTS = { terrain: "00-history.json", ground: "35-history.json", notes: "65-history.json" };
const ERAS = ["before", "now"];
const HEADER = "Generated by scripts/history.mjs from world/history/events.json: edit the ledger, not this file.";

/** Deterministic 0-1 hash of a string, so an event's outline wobble never changes between builds */
function hash(text, salt = 0) {
  let h = 2166136261 ^ salt;
  for (const ch of text) h = Math.imul(h ^ ch.charCodeAt(0), 16777619);
  return ((h >>> 0) % 100000) / 100000;
}

/**
 * A lopsided ellipse (regions are never clean shapes) in frame-local 0-1 coordinates.
 * Shapes are given in km and converted per axis, so a circle stays a circle on the map (azgaar-ops M3).
 */
function outline({ centerKm, radiiKm, angle = 0 }, frameKm, key, growKm = 0, points = 32) {
  const [cx, cy] = centerKm;
  const [rx, ry] = radiiKm.map(r => r + growKm);
  const a = (angle * Math.PI) / 180;
  const phase = [hash(key, 1), hash(key, 2), hash(key, 3)].map(v => v * 2 * Math.PI);
  const poly = [];
  for (let i = 0; i < points; i++) {
    const t = (i / points) * 2 * Math.PI;
    const wobble = 1 + 0.1 * Math.sin(2 * t + phase[0]) + 0.06 * Math.sin(3 * t + phase[1]) + 0.04 * Math.sin(5 * t + phase[2]);
    const x = rx * wobble * Math.cos(t);
    const y = ry * wobble * Math.sin(t);
    const kmX = cx + x * Math.cos(a) - y * Math.sin(a);
    const kmY = cy + x * Math.sin(a) + y * Math.cos(a);
    poly.push([round(kmX / frameKm[0]), round(kmY / frameKm[1])]);
  }
  return poly;
}
const round = v => Math.round(v * 10000) / 10000;
const local = ([x, y], frameKm) => [round(x / frameKm[0]), round(y / frameKm[1])];

function eventNote(event, era, ledger, extra) {
  const yearsAgo = ledger.eras[event.era]?.yearsAgo;
  return [
    `<b>${event.name}</b> (${event.status}${event.status === "canon" && event.source ? `: ${event.source}` : ""})`,
    `When: about ${yearsAgo} years ago (${event.era} era).`,
    event.story,
    extra
  ].filter(Boolean).join("<br>");
}

/** Aging rules per event kind: each returns ops for both eras, by slot */
const KINDS = {
  /**
   * An extraction works draws the ground dry. Real analogues: groundwater pumping makes land subside over the drained
   * aquifer (Mexico City, California's Central Valley); a lake that loses its water table dries to a flat playa floored
   * with fine sediment and salts (Owens Lake); waterlogged marsh soil is gleyed blue-grey, and once it dries the air
   * rusts its iron into orange mottles, so a dead marsh leaves a grey-blue, rust-streaked ring around the old shore.
   */
  "extraction-drain"(event, frameKm, ledger) {
    const { shape, params = {} } = event;
    const frame = event.frame;
    const subsidence = params.subsidence ?? 3;
    const playa = params.playaHeight ?? 26;
    const lake = outline(shape.lake, frameKm, `${event.id}.lake`);
    const marsh = outline(shape.lake, frameKm, `${event.id}.lake`, shape.marshKm ?? 4);
    const drawdown = outline(shape.drawdown, frameKm, `${event.id}.drawdown`);
    const works = local(shape.worksKm, frameKm);
    const lakeCenter = local(shape.lake.centerKm, frameKm);
    const id = event.id;
    return {
      before: {
        terrain: [
          {
            id: `${id}.before.lake`,
            tool: "sculpt",
            note: "The lake as it stood: a shallow pit below height 20, so finalize_terrain makes it a lake (azgaar-ops M1)",
            args: { frame, polygon: lake, op: "set", value: 17, feather_km: 1, edge_noise_km: 0 }
          }
        ],
        ground: [
          {
            id: `${id}.before.marsh`,
            tool: "paint_biome",
            note: "The living marsh around the shore: the waterlogged ground that will be gleyed",
            args: { frame, name: "Wetland", polygon: marsh, heights: [20, 100] }
          },
          {
            id: `${id}.before.lake-name`,
            tool: "set_lakes",
            note: "The lake, fresh while the water table fed it",
            args: { frame, polygon: lake, subtype: "freshwater", name: `${event.name} (living)` }
          }
        ],
        notes: [
          {
            id: `${id}.before.works`,
            tool: "add_marker",
            note: "The works at work",
            args: { frame, point: works, type: "history", icon: "⚙️", name: `${event.name}: the works`, note: eventNote(event, "before", ledger, "Shown as it stood.") }
          }
        ]
      },
      now: {
        terrain: [
          {
            id: `${id}.now.subsidence`,
            tool: "sculpt",
            note: `The ground over the drained aquifer sank ${subsidence} height units across the drained area, fading out over a wide edge; kept above the shoreline so no new lake forms`,
            args: { frame, polygon: drawdown, op: "lower", value: subsidence, feather_km: 8, clamp: [21, 100] }
          },
          {
            id: `${id}.now.playa`,
            tool: "sculpt",
            note: `The lake bed, dried and silted to a flat playa at ${playa}: lower than its old shore, never below 20 so it stays dry`,
            args: { frame, polygon: lake, op: "set", value: playa, feather_km: 1.5, clamp: [21, 100] }
          }
        ],
        ground: [
          {
            id: `${id}.now.gley`,
            tool: "paint_biome",
            note: "The dead marsh: gleyed blue-grey soil rusted orange where it dried (Gaea: mask-biome-relict-gley)",
            args: { frame, name: "Relict Gley", color: "#8C9A99", habitability: 2, polygon: marsh, heights: [20, 100] }
          },
          {
            id: `${id}.now.playa-crust`,
            tool: "paint_biome",
            note: "The dry lake bed: pale silt and salt crust (Gaea: mask-biome-dry-lakebed)",
            args: { frame, name: "Dry Lakebed", color: "#E6DFCD", habitability: 0, polygon: lake, heights: [20, 100] }
          }
        ],
        notes: [
          {
            id: `${id}.now.works`,
            tool: "add_marker",
            note: "What is left of the works",
            args: { frame, point: works, type: "ruins", name: `${event.name}: the works (ruin)`, note: eventNote(event, "now", ledger, "Stone footings only; the metal rusted to stains.") }
          },
          {
            id: `${id}.now.label`,
            tool: "add_label",
            note: "The dry lake's name, with the event as its note",
            args: { frame, point: lakeCenter, text: event.name, note: eventNote(event, "now", ledger) }
          }
        ]
      }
    };
  }
};

export function compileHistory() {
  const ledger = JSON.parse(readFileSync(join(root, "world/history/events.json"), "utf8"));
  const frames = JSON.parse(readFileSync(join(root, "world/frames.json"), "utf8"));
  const out = Object.fromEntries(ERAS.map(era => [era, { terrain: [], ground: [], notes: [] }]));
  const ids = new Set();
  for (const event of ledger.events) {
    if (ids.has(event.id)) throw new Error(`Duplicate event id "${event.id}"`);
    ids.add(event.id);
    if (!["test", "proposed", "canon"].includes(event.status)) throw new Error(`Event "${event.id}": status must be test, proposed or canon`);
    if (!ledger.eras[event.era]) throw new Error(`Event "${event.id}": unknown era "${event.era}"`);
    const rules = KINDS[event.kind];
    if (!rules) throw new Error(`Event "${event.id}": unknown kind "${event.kind}" (known: ${Object.keys(KINDS).join(", ")})`);
    const frame = frames[event.frame];
    if (!frame) throw new Error(`Event "${event.id}": unknown frame "${event.frame}"`);
    const ops = rules(event, frame.sizeKm, ledger);
    for (const era of ERAS) for (const slot of Object.keys(SLOTS)) out[era][slot].push(...(ops[era]?.[slot] ?? []));
  }
  const written = [];
  for (const era of ERAS) {
    if (out[era].terrain.length) out[era].terrain.push({ id: `history.${era}.finalize`, tool: "finalize_terrain", note: "Rebuild lakes, rivers and biomes from the aged terrain, before the era's climate and water", args: {} });
    for (const [slot, file] of Object.entries(SLOTS)) {
      const path = join(root, "world/eras", era, file);
      const ops = out[era][slot];
      if (!ops.length) {
        if (existsSync(path)) rmSync(path);
        continue;
      }
      writeFileSync(path, JSON.stringify(ops.map(op => ({ ...op, generated: HEADER })), null, 2) + "\n");
      written.push(`world/eras/${era}/${file}`);
    }
  }
  return written;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  console.log(`History ops written: ${compileHistory().join(", ") || "none"}`);
}
